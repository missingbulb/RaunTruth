// Under Node, the decoders the page takes from jsDelivr come from web-tests/node_modules instead, where the full CI
// set installs them at the same versions: an import resolves to the package's own file (jsDelivr's /+esm wrapper of
// a CommonJS file being that file, which Node imports as it is), and a fetch of one of its files, or of Pyodide's
// packages, reads it from disk.
// Imported before the page's modules.
import { register } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { local as installed } from "./fakes/cdn.mjs";

const CDN = "https://cdn.jsdelivr.net/npm/", JSDELIVR = "https://cdn.jsdelivr.net/";
const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), "node_modules");
// by the folder's own path, where it is a link (the test image's): a package file reached through the link is not
// taken as its package's, and a CommonJS one loses its default export
register("data:text/javascript," + encodeURIComponent(`
const CDN = ${JSON.stringify(CDN)}, HERE = ${JSON.stringify(pathToFileURL(fs.existsSync(dir) ? fs.realpathSync(dir) : dir).href + "/")};
export async function resolve(spec, ctx, next) {
  return spec.startsWith(CDN) ? { url: HERE + spec.slice(CDN.length).replace(/^((?:@[^/]+\\/)?[^@/]+)@[^/]+/, "$1").replace(/\\/\\+esm$/, ""), shortCircuit: true } : next(spec, ctx);
}`));
// a fetch from jsDelivr, a package's file or Pyodide's, answered as the page tests' fake of it answers (fakes/cdn.mjs)
const fetched = globalThis.fetch;
globalThis.fetch = async (u, init) => {
  const href = String(u?.url ?? u);
  if (!href.startsWith(JSDELIVR)) return fetched(u, init);
  const f = installed(href);
  return f && fs.existsSync(f) && fs.statSync(f).isFile() ? new Response(fs.readFileSync(f)) : new Response("", { status: 404 });
};

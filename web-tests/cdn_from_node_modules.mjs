// Under Node, the decoders the page takes from jsDelivr come from web-tests/node_modules instead, where the full CI
// set installs them at the same versions: an import resolves to the package's own file (jsDelivr's /+esm wrapper of
// a CommonJS file being that file, which Node imports as it is), and a fetch of one of its files reads it from disk.
// Imported before the page's modules.
import { register } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const CDN = "https://cdn.jsdelivr.net/npm/";
const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), "node_modules");
const local = (u) => u.slice(CDN.length).replace(/^((?:@[^/]+\/)?[^@/]+)@[^/]+/, "$1").replace(/\/\+esm$/, "");
register("data:text/javascript," + encodeURIComponent(`
const CDN = ${JSON.stringify(CDN)}, HERE = ${JSON.stringify(pathToFileURL(dir).href + "/")};
export async function resolve(spec, ctx, next) {
  return spec.startsWith(CDN) ? { url: HERE + spec.slice(CDN.length).replace(/^((?:@[^/]+\\/)?[^@/]+)@[^/]+/, "$1").replace(/\\/\\+esm$/, ""), shortCircuit: true } : next(spec, ctx);
}`));
const fetched = globalThis.fetch;
globalThis.fetch = async (u, init) => {
  const href = String(u?.url ?? u);
  if (!href.startsWith(CDN)) return fetched(u, init);
  const f = path.join(dir, local(href));
  return fs.existsSync(f) ? new Response(fs.readFileSync(f)) : new Response("", { status: 404 });
};
